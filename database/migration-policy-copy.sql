- **ទីតាំងពីទូរស័ព្ទរបស់អ្នក** — នៅក្នុងកម្មវិធី teepsaa តែពេលអ្នកចុច «រកទីតាំងខ្ញុំ» ពេលកំណត់អាសយដ្ឋានដឹកជញ្ជូនប៉ុណ្ណោះ។ វាត្រូវបានប្រើម្តង ដើម្បីដាក់ចំណុចលើផែនទី ហើយមានតែចំណុចដែលអ្នករក្សាទុកប៉ុណ្ណោះដែលត្រូវបានរក្សាទុក។
- **ព័ត៌មានឧបករណ៍** — ប្រសិនបើអ្នកអនុញ្ញាតការជូនដំណឹងនៅក្នុងកម្មវិធីរបស់យើង token ជូនដំណឹងសម្រាប់ទូរស័ព្ទរបស់អ្នក ដើម្បីឱ្យយើងអាចផ្ញើព័ត៌មានថ្មីៗអំពីកម្មង់។ វាត្រូវបានលុបពេលអ្នកចាកចេញ។
- **ប្រវត្តិកម្មង់** — ទំនិញដែលបានកម្មង់ តម្លៃដែលបានបង់ ស្ថានភាពកម្មង់ និងពេលវេលា
- **កំណត់ត្រាការបង់ប្រាក់** — ភស្តុតាងនៃការផ្ទេរប្រាក់ធនាគារ ABA ដែលអ្នកទិញដាក់ស្នើ។ យើងមិនរក្សាទុកលេខកាត ឬព័ត៌មានសម្ងាត់ធនាគារទេ។
- **ព័ត៌មានអាជីវកម្ម** — សម្រាប់អ្នកលក់៖ ឈ្មោះអាជីវកម្ម ទីតាំង កូដ QR ABA សម្រាប់ការទូទាត់ និងបញ្ជីផលិតផល

