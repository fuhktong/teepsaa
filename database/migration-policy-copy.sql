## ៦. ការរក្សាទុកទិន្នន័យ
ទិន្នន័យរបស់អ្នកត្រូវបានរក្សាទុករយៈពេលដែលគណនីរបស់អ្នកនៅសកម្ម។ ពេលអ្នកលុបគណនី វាមិនអាចចូលបានទៀតទេ ហើយប្រវត្តិរូបរបស់អ្នកឈប់បង្ហាញ — សម្រាប់អ្នកលក់ ហាង និងផលិតផលរបស់វាផងដែរ។ ឈ្មោះ អាសយដ្ឋានអ៊ីមែល លេខទូរស័ព្ទ រូបថត អាសយដ្ឋាន ទំនិញដែលបានរក្សាទុក សារមកយើង ហើយសម្រាប់អ្នកលក់ QR ធនាគារ និងអាសយដ្ឋានហាង ត្រូវបានលុប។ កម្មង់ ការបង់ប្រាក់ ការទូទាត់ ការសងប្រាក់វិញ និងការវាយតម្លៃ ត្រូវបានរក្សាទុកជាកំណត់ត្រាគណនេយ្យ ដោយគ្មានព័ត៌មានផ្ទាល់ខ្លួនរបស់អ្នក ក្រោមឈ្មោះ «គណនីដែលបានលុប»។ ការលុបមិនអាចត្រឡប់វិញបានទេ ហើយគណនីដែលមានកម្មង់កំពុងដំណើរការ មិនអាចលុបបានទេ រហូតដល់កម្មង់នោះបញ្ចប់។ របៀបលុបគណនី នៅក្នុងកម្មវិធី ឬនៅលើគេហទំព័រ៖ [លុបគណនីរបស់អ្នក](/delete-account/)។

ប្រសិនបើគណនីមួយត្រូវបានផ្អាក ដោយសារការបំពានច្បាប់របស់យើង ឬច្បាប់ យើងរក្សាទុកកូដសម្គាល់ដែលបានបំប្លែង នៃអាសយដ្ឋានអ៊ីមែល និងលេខទូរស័ព្ទរបស់គណនីនោះ ទោះបីជាគណនីត្រូវបានលុបហើយក៏ដោយ។ កូដនេះមិនអាចបំប្លែងត្រឡប់ទៅជាអ៊ីមែល ឬលេខទូរស័ព្ទវិញបានទេ វាគ្រាន់តែជួយឱ្យយើងស្គាល់ព័ត៌មានដដែល ប្រសិនបើវាត្រូវបានប្រើដើម្បីចុះឈ្មោះម្តងទៀត។ កូដនេះត្រូវបានលុបចោល ប្រសិនបើការផ្អាកត្រូវបានដកចេញ។

